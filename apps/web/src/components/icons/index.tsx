import type { SVGProps } from 'react';

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'children'> {
  size?: number | string;
  strokeWidth?: number;
}

interface IconPath {
  d: string;
  width?: number;
  cap?: 'round' | 'square' | 'butt';
  join?: 'round' | 'miter' | 'bevel';
}

function createIcon(name: string, grid: number, paths: IconPath[]) {
  function Icon({ size = grid, strokeWidth, ...rest }: IconProps) {
    return (
      <svg
        width={size}
        height={size}
        viewBox={`0 0 ${grid} ${grid}`}
        fill="none"
        stroke="currentColor"
        aria-hidden="true"
        focusable="false"
        {...rest}
      >
        {paths.map((p, i) => (
          <path
            key={i}
            d={p.d}
            strokeWidth={strokeWidth ?? p.width ?? 1}
            strokeLinecap={p.cap}
            strokeLinejoin={p.join}
          />
        ))}
      </svg>
    );
  }
  Icon.displayName = name;
  return Icon;
}

